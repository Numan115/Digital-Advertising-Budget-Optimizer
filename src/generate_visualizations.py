"""
generate_visualizations.py
Creates 10 comprehensive visualizations for Part 1 Exploratory Data Analysis.
Saved in: visualizations/
"""

import os
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Set style
sns.set_theme(style='whitegrid')
plt.rcParams['font.sans-serif'] = 'Arial'
plt.rcParams['font.family'] = 'sans-serif'

def create_visualizations(input_path='data/processed/advertising_data_with_kpis.csv',
                          output_dir='visualizations'):
    os.makedirs(output_dir, exist_ok=True)
    df = pd.read_csv(input_path)
    df['date'] = pd.to_datetime(df['date'])
    
    # 1. Platform ROAS Comparison
    plt.figure(figsize=(10, 6))
    platform_roas = df.groupby('platform')['roas'].mean().sort_values(ascending=False).reset_index()
    palette = ['#2b5c8f', '#36827f', '#4ca585', '#d4a373', '#e76f51']
    ax = sns.barplot(data=platform_roas, x='platform', y='roas', palette=palette)
    plt.title('Average Return on Ad Spend (ROAS) by Platform', fontsize=15, fontweight='bold', pad=15)
    plt.xlabel('Advertising Platform', fontsize=12)
    plt.ylabel('Average ROAS (Rs. Revenue per Rs. 1 Spend)', fontsize=12)
    for p in ax.patches:
        ax.annotate(f"{p.get_height():.2f}x",
                    (p.get_x() + p.get_width() / 2., p.get_height()),
                    ha='center', va='bottom', fontsize=11, fontweight='bold', xytext=(0, 4),
                    textcoords='offset points')
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '01_platform_roas_comparison.png'), dpi=300)
    plt.close()

    # 2. Spend vs Revenue by Platform
    plt.figure(figsize=(11, 6))
    spend_rev = df.groupby('platform')[['spend', 'revenue']].sum() / 1e6 # in Millions PKR
    spend_rev = spend_rev.reset_index().melt(id_vars='platform', value_vars=['spend', 'revenue'], 
                                            var_name='Metric', value_name='Amount_Millions')
    spend_rev['Metric'] = spend_rev['Metric'].replace({'spend': 'Total Spend (Rs. M)', 'revenue': 'Total Revenue (Rs. M)'})
    ax = sns.barplot(data=spend_rev, x='platform', y='Amount_Millions', hue='Metric', palette=['#e63946', '#2a9d8f'])
    plt.title('Total Advertising Spend vs. Revenue Generated by Platform (PKR Millions)', fontsize=14, fontweight='bold', pad=15)
    plt.xlabel('Platform', fontsize=12)
    plt.ylabel('Amount (PKR Millions)', fontsize=12)
    plt.legend(title='')
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '02_spend_vs_revenue_by_platform.png'), dpi=300)
    plt.close()

    # 3. Conversion Rate & CTR Comparison
    fig, ax1 = plt.subplots(figsize=(10, 6))
    platform_rates = df.groupby('platform')[['ctr', 'conversion_rate']].mean().reset_index()
    width = 0.35
    x = np.arange(len(platform_rates))
    rects1 = ax1.bar(x - width/2, platform_rates['ctr'], width, label='Click-Through Rate (CTR %)', color='#457b9d')
    rects2 = ax1.bar(x + width/2, platform_rates['conversion_rate'], width, label='Conversion Rate (%)', color='#2a9d8f')
    ax1.set_ylabel('Percentage (%)', fontsize=12)
    ax1.set_title('Average CTR vs. Conversion Rate by Platform', fontsize=14, fontweight='bold', pad=15)
    ax1.set_xticks(x)
    ax1.set_xticklabels(platform_rates['platform'], fontsize=11)
    ax1.legend()
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '03_ctr_vs_conversion_rate.png'), dpi=300)
    plt.close()

    # 4. CPC & CPA Cost Metrics Comparison
    plt.figure(figsize=(10, 6))
    cost_df = df.groupby('platform').agg(
        overall_cpa=('spend', lambda s: s.sum() / df.loc[s.index, 'conversions'].sum()),
        avg_cpc=('cpc', 'mean')
    ).reset_index()
    ax = sns.barplot(data=cost_df, x='platform', y='overall_cpa', palette='Blues_r')
    plt.title('Cost Per Acquisition (CPA) by Platform (Lower is Better)', fontsize=14, fontweight='bold', pad=15)
    plt.xlabel('Platform', fontsize=12)
    plt.ylabel('CPA (Rs. per Acquisition)', fontsize=12)
    for p in ax.patches:
        ax.annotate(f"Rs. {p.get_height():.0f}",
                    (p.get_x() + p.get_width() / 2., p.get_height()),
                    ha='center', va='bottom', fontsize=10, fontweight='bold', xytext=(0, 4),
                    textcoords='offset points')
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '04_cpa_by_platform.png'), dpi=300)
    plt.close()

    # 5. Campaign Performance by ROAS
    plt.figure(figsize=(12, 6))
    camp_roas = df.groupby('campaign')['roas'].mean().sort_values(ascending=False).reset_index()
    ax = sns.barplot(data=camp_roas, y='campaign', x='roas', palette='viridis')
    plt.title('Performance by Campaign Type: Average ROAS', fontsize=14, fontweight='bold', pad=15)
    plt.xlabel('Average ROAS', fontsize=12)
    plt.ylabel('Campaign Name', fontsize=12)
    for p in ax.patches:
        ax.annotate(f"{p.get_width():.2f}x",
                    (p.get_width(), p.get_y() + p.get_height() / 2.),
                    ha='left', va='center', fontsize=10, fontweight='bold', xytext=(5, 0),
                    textcoords='offset points')
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '05_campaign_performance_roas.png'), dpi=300)
    plt.close()

    # 6. Audience Demographics: Age Group vs Gender ROAS Heatmap
    plt.figure(figsize=(9, 6))
    demo_pivot = df.pivot_table(index='age', columns='gender', values='roas', aggfunc='mean')
    sns.heatmap(demo_pivot, annot=True, fmt='.2f', cmap='YlGnBu', cbar_kws={'label': 'Average ROAS'})
    plt.title('Audience Segment ROAS: Age Group × Gender', fontsize=14, fontweight='bold', pad=15)
    plt.xlabel('Gender', fontsize=12)
    plt.ylabel('Age Bracket', fontsize=12)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '06_demographics_heatmap.png'), dpi=300)
    plt.close()

    # 7. City-wise Revenue Generation in Pakistan
    plt.figure(figsize=(12, 6))
    city_summary = (df.groupby('city')['revenue'].sum() / 1e6).sort_values(ascending=True).reset_index()
    ax = sns.barplot(data=city_summary, y='city', x='revenue', palette='mako')
    plt.title('Total Revenue Generated across Pakistani Cities (PKR Millions)', fontsize=14, fontweight='bold', pad=15)
    plt.xlabel('Total Revenue (PKR Millions)', fontsize=12)
    plt.ylabel('City', fontsize=12)
    for p in ax.patches:
        ax.annotate(f"Rs. {p.get_width():.1f}M",
                    (p.get_width(), p.get_y() + p.get_height() / 2.),
                    ha='left', va='center', fontsize=10, fontweight='bold', xytext=(5, 0),
                    textcoords='offset points')
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '07_city_revenue_performance.png'), dpi=300)
    plt.close()

    # 8. Device Share (Pie / Donut)
    plt.figure(figsize=(7, 7))
    device_counts = df['device'].value_counts()
    colors = ['#2b5c8f', '#4ca585', '#e76f51']
    plt.pie(device_counts, labels=device_counts.index, autopct='%1.1f%%', startangle=140, 
            colors=colors, explode=[0.05, 0, 0], wedgeprops=dict(width=0.6))
    plt.title('Ad Impressions & Engagement by Device Type', fontsize=14, fontweight='bold', pad=15)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '08_device_distribution_donut.png'), dpi=300)
    plt.close()

    # 9. Monthly Revenue and Spend Trend (2023 - 2024)
    plt.figure(figsize=(13, 6))
    monthly_trend = df.set_index('date').resample('ME')[['spend', 'revenue']].sum() / 1e6
    plt.plot(monthly_trend.index, monthly_trend['revenue'], label='Monthly Revenue (Rs. M)', color='#2a9d8f', linewidth=2.5, marker='o')
    plt.plot(monthly_trend.index, monthly_trend['spend'], label='Monthly Spend (Rs. M)', color='#e63946', linewidth=2, linestyle='--', marker='s')
    plt.title('Monthly Marketing Spend vs. Revenue Trend (2023–2024)', fontsize=14, fontweight='bold', pad=15)
    plt.xlabel('Month', fontsize=12)
    plt.ylabel('Amount (PKR Millions)', fontsize=12)
    plt.legend(fontsize=11)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '09_monthly_performance_trend.png'), dpi=300)
    plt.close()

    # 10. Platform x Day of Week Engagement Heatmap
    plt.figure(figsize=(11, 6))
    days_order = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday']
    dow_pivot = df.pivot_table(index='platform', columns='day_of_week', values='roas', aggfunc='mean')[days_order]
    sns.heatmap(dow_pivot, annot=True, fmt='.2f', cmap='coolwarm', cbar_kws={'label': 'Average ROAS'})
    plt.title('Platform ROAS by Day of Week', fontsize=14, fontweight='bold', pad=15)
    plt.xlabel('Day of Week', fontsize=12)
    plt.ylabel('Platform', fontsize=12)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, '10_platform_day_of_week_roas.png'), dpi=300)
    plt.close()

    print(f"Generated 10 visualizations successfully inside: {output_dir}")

if __name__ == '__main__':
    create_visualizations()
